"""Prepare the Homebrew release files. This script does not publish files."""
import argparse
import difflib
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tomllib

DIST_VERSION = "0.33.1"
ROOT = Path(__file__).resolve().parents[1]
WORKFLOW_MARKER = "# Release workflow. Use scripts/configure_homebrew.py to update this file."


def repository(value):
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]*/[A-Za-z0-9][A-Za-z0-9_.-]*", value):
        raise argparse.ArgumentTypeError("Use the GitHub owner/repository format. Do not include a URL or .git suffix.")
    if value.endswith(".git") or any(part in {".", ".."} for part in value.split("/")):
        raise argparse.ArgumentTypeError("Use the GitHub owner/repository format without a .git suffix.")
    return value


def tap(value):
    value = repository(value)
    name = value.split("/", 1)[1]
    if not name.startswith("homebrew-") or name == "homebrew-":
        raise argparse.ArgumentTypeError("Use homebrew-<name> for the tap repository name.")
    return value


def cargo_metadata(text, name):
    tomllib.loads(text)
    section = re.search(r"(?ms)^\[package\][ \t]*\n(.*?)(?=^\[|\Z)", text)
    if not section:
        raise ValueError("Cargo.toml does not contain a [package] section.")
    package = section.group(1)
    url = "https://github.com/" + name
    for key in ("repository", "homepage"):
        pattern = rf"(?m)^{key}\s*=.*$"
        line = f"{key} = {json.dumps(url)}"
        if re.search(pattern, package):
            if key == "repository":
                package = re.sub(pattern, lambda _: line, package)
        else:
            package = package.rstrip() + "\n" + line + "\n\n"
    result = text[:section.start(1)] + package + text[section.end(1):]
    assert tomllib.loads(result)["package"]["repository"] == url
    return result


def workflow_text(text):
    lines = text.splitlines()
    notices = [line for line in lines if line.startswith(("# Copyright ", "# SPDX-License-Identifier:"))]
    body = "\n".join(line for line in lines if not line.lstrip().startswith("#")).lstrip()
    replacements = {
        'echo "dist ran successfully"': 'echo "The command completed."',
        'echo "artifacts uploaded and released successfully"': 'echo "The release files are available."',
        'name: enable windows longpaths': 'name: Enable long Windows paths',
        'name: Install Rust non-interactively if not already installed': 'name: Install Rust if necessary',
        'name: Post-build': 'name: Read the build results',
    }
    for previous, current in replacements.items():
        body = body.replace(previous, current)
    return "\n".join([WORKFLOW_MARKER, *notices, "", body.rstrip(), ""])


def restore(backups):
    for path, previous in backups.items():
        if previous is None:
            path.unlink(missing_ok=True)
        else:
            path.write_bytes(previous)


def configure(root, repo, homebrew_tap, dist, dry_run=False, check=False):
    manifest = root / "Cargo.toml"
    config = root / "dist-workspace.toml"
    workflow = root / ".github/workflows/release.yml"
    desired_manifest = cargo_metadata(manifest.read_text(), repo)
    desired_config = (root / "packaging/dist-workspace.toml.in").read_text().replace("@HOMEBREW_TAP@", homebrew_tap)
    parsed = tomllib.loads(desired_config)
    assert parsed["dist"]["tap"] == homebrew_tap
    if config.exists():
        existing = tomllib.loads(config.read_text())
        existing.setdefault("dist", {}).setdefault("allow-dirty", ["ci"])
        if existing != parsed:
            raise ValueError("dist-workspace.toml contains different settings. Examine the file before you change the configuration.")
    if workflow.exists():
        current = workflow.read_text()
        if WORKFLOW_MARKER not in current and "This file was autogenerated by dist:" not in current:
            raise ValueError("The release workflow contains manual changes. This script will not overwrite it.")
    desired = {manifest: desired_manifest, config: desired_config}
    if dry_run:
        for path, content in desired.items():
            previous = path.read_text() if path.exists() else ""
            sys.stdout.writelines(difflib.unified_diff(previous.splitlines(True), content.splitlines(True),
                fromfile=str(path.relative_to(root)), tofile=str(path.relative_to(root))))
        print("The script will generate .github/workflows/release.yml. This preview does not change files.")
        return
    executable = shutil.which(dist)
    if executable is None:
        raise ValueError(f"Install dist {DIST_VERSION} first. You can also use --dist to specify the executable path.")
    version = subprocess.run([executable, "--version"], capture_output=True, text=True, check=True).stdout.strip()
    if version != f"cargo-dist {DIST_VERSION}":
        raise ValueError(f"Use cargo-dist {DIST_VERSION}. The installed version is {version}.")
    backups = {path: path.read_bytes() if path.exists() else None for path in (*desired, workflow)}
    try:
        manifest.write_text(desired_manifest)
        # Generate the original workflow. Compare it with the generator output.
        config.write_text(desired_config.replace('allow-dirty = ["ci"]\n', ""))
        subprocess.run([executable, "generate"], cwd=root, check=True)
        subprocess.run([executable, "generate", "--check"], cwd=root, check=True)
        desired[workflow] = workflow_text(workflow.read_text())
        for path, content in desired.items():
            path.write_text(content)
        if check:
            if any(backups[path] != content.encode() for path, content in desired.items()):
                raise ValueError("The release files are not current. Use this command without --check to update them.")
    except BaseException:
        restore(backups)
        raise
    if check:
        restore(backups)
        print("The release files match the configuration.")
    else:
        print("The release files are complete. This script did not publish files.")
        print(f"After publication, use: brew install {homebrew_tap.replace('/homebrew-', '/', 1)}/gfs")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository", type=repository, required=True, help="The app repository: owner/repository")
    parser.add_argument("--tap", type=tap, required=True, help="The tap repository: owner/homebrew-name")
    parser.add_argument("--dist", default="dist", help=f"The path to dist {DIST_VERSION}")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="Show a preview without file changes")
    mode.add_argument("--check", action="store_true", help="Compare the release files with the configuration")
    args = parser.parse_args()
    try:
        configure(ROOT, args.repository, args.tap, args.dist, args.dry_run, args.check)
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        parser.exit(1, f"Cannot prepare the release files: {error}\n")


if __name__ == "__main__":
    main()
